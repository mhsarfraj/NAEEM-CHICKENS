def forward(route, request):
    url=request.url.replace(GAS, BASE+'/exec')
    req=urllib.request.Request(url, data=request.post_data.encode() if request.post_data else None, method=request.method)
    with urllib.request.urlopen(req) as r: body=r.read()
    route.fulfill(status=200, body=body, headers={'Access-Control-Allow-Origin':'*','Content-Type':'application/json'})
def api(action, **d):
    req=urllib.request.Request(BASE+'/exec', data=json.dumps({'action':action, **d}).encode(), method='POST')
    return json.load(urllib.request.urlopen(req))
